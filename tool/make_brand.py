#!/usr/bin/env python3
"""Generates the app icon (DESIGN.md 12) from one description of its shapes.

Dev-time only (needs Pillow; nothing here ships). Writes, under
android/app/src/main/res: the adaptive icon's foreground and monochrome vector
drawables, the adaptive icon itself (API 26+), and the legacy launcher PNGs
(API 24-25). Run from the repo root: python3 tool/make_brand.py

The mark: a five-segment fragment of the tach arc with the last segment lit and
glowing, above a short chamfered strip, on the `void` colour. Colours are the
ION livery's tokens (lib/ui/design/tokens/livery.dart, colors.dart).
"""
import math
import os

from PIL import Image, ImageDraw

RES = "android/app/src/main/res"
VOID = "#050607"
ION_CORE = "#5CE1FF"
ION_GLOW = "#2EC8FF"
ION_DEEP = "#1296FF"
UNLIT = "#4B5563"

# The 108 dp adaptive canvas; the guaranteed-visible circle is 66 dp across.
CX, CY, R, W = 54.0, 60.0, 27.0, 9.0
START, SEG, GAP, N = -148.0, 20.0, 4.0, 5
STRIP = [(45, 72), (68, 72), (68, 75), (65, 77), (42, 77), (42, 74)]  # chamfered


def seg_angles(i):
    a0 = START + i * (SEG + GAP)
    return a0, a0 + SEG


def pt(r, deg):
    t = math.radians(deg)
    return CX + r * math.cos(t), CY + r * math.sin(t)


def arc_path(r, a0, a1):
    x0, y0 = pt(r, a0)
    x1, y1 = pt(r, a1)
    return f"M{x0:.2f},{y0:.2f} A{r},{r} 0 0 1 {x1:.2f},{y1:.2f}"


def strip_path():
    return "M" + " L".join(f"{x},{y}" for x, y in STRIP) + " Z"


def vector(body, tint=False):
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<!-- Generated by tool/make_brand.py. Do not edit by hand. -->\n"
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    android:width="108dp" android:height="108dp"\n'
        '    android:viewportWidth="108" android:viewportHeight="108">\n'
        + body
        + "</vector>\n"
    )


def stroke(path, color, width, alpha=1.0):
    a = f'\n        android:strokeAlpha="{alpha}"' if alpha != 1.0 else ""
    return (
        f'    <path android:pathData="{path}"\n'
        f'        android:strokeColor="{color}" android:strokeWidth="{width}"{a} />\n'
    )


def fill(path, color, alpha=1.0):
    a = f'\n        android:fillAlpha="{alpha}"' if alpha != 1.0 else ""
    return f'    <path android:pathData="{path}"\n        android:fillColor="{color}"{a} />\n'


def foreground():
    body = ""
    for i in range(N - 1):
        body += stroke(arc_path(R, *seg_angles(i)), UNLIT, W)
    a0, a1 = seg_angles(N - 1)
    # The glow: wider, fainter strokes round the lit segment (a vector cannot
    # blur), then the segment itself.
    for width, alpha in ((W + 9, 0.10), (W + 5, 0.18), (W + 2, 0.30)):
        body += stroke(arc_path(R, a0, a1), ION_GLOW, width, alpha)
    body += stroke(arc_path(R, a0, a1), ION_CORE, W)
    body += fill(strip_path(), ION_DEEP)
    return vector(body)


def monochrome():
    body = ""
    for i in range(N - 1):
        body += stroke(arc_path(R, *seg_angles(i)), "#FFFFFF", W, 0.45)
    a0, a1 = seg_angles(N - 1)
    body += stroke(arc_path(R, a0, a1), "#FFFFFF", W)
    body += fill(strip_path(), "#FFFFFF")
    return vector(body)


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write(text)


def legacy(px):
    """The same mark, drawn for a square legacy icon of px pixels."""
    ss = 4
    size = px * ss
    img = Image.new("RGB", (size, size), VOID)
    d = ImageDraw.Draw(img, "RGBA")
    # The 108 canvas is cropped to its central 72: a legacy icon has no mask,
    # so the mark can use the whole square.
    scale = size / 72.0
    ox = oy = -18.0

    def tx(x, y):
        return ((x + ox) * scale, (y + oy) * scale)

    def draw_arc(r, a0, a1, width, color):
        # A filled ring segment, not a thick line: crisp edges at every size.
        n = 32
        outer = [pt(r + width / 2, a0 + (a1 - a0) * k / n) for k in range(n + 1)]
        inner = [pt(r - width / 2, a0 + (a1 - a0) * k / n) for k in range(n, -1, -1)]
        d.polygon([tx(*p) for p in outer + inner], fill=color)

    def rgb(h, a=255):
        h = h.lstrip("#")
        return (int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16), a)

    for i in range(N - 1):
        draw_arc(R, *seg_angles(i), W, rgb(UNLIT))
    a0, a1 = seg_angles(N - 1)
    for width, alpha in ((W + 9, 26), (W + 5, 46), (W + 2, 77)):
        draw_arc(R, a0, a1, width, rgb(ION_GLOW, alpha))
    draw_arc(R, a0, a1, W, rgb(ION_CORE))
    d.polygon([tx(x, y) for x, y in STRIP], fill=rgb(ION_DEEP))
    return img.resize((px, px), Image.LANCZOS)


def main():
    write(f"{RES}/drawable/ic_launcher_foreground.xml", foreground())
    write(f"{RES}/drawable/ic_launcher_monochrome.xml", monochrome())
    write(
        f"{RES}/mipmap-anydpi-v26/ic_launcher.xml",
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<!-- Generated by tool/make_brand.py. -->\n"
        '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
        '    <background android:drawable="@color/tapedash_void" />\n'
        '    <foreground android:drawable="@drawable/ic_launcher_foreground" />\n'
        '    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />\n'
        "</adaptive-icon>\n",
    )
    for name, px in (("mdpi", 48), ("hdpi", 72), ("xhdpi", 96), ("xxhdpi", 144), ("xxxhdpi", 192)):
        legacy(px).save(f"{RES}/mipmap-{name}/ic_launcher.png")
    legacy(512).save("docs/brand-icon-preview.png")
    print("brand written")


if __name__ == "__main__":
    main()
